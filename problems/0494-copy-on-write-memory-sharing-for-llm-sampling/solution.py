import math

def cow_memory_simulator(prompt_length: int, num_sequences: int, gen_lengths: list, block_size: int) -> dict:
    """
    Simulate copy-on-write memory management for parallel LLM sampling.
    
    Args:
        prompt_length: Number of tokens in the shared prompt
        num_sequences: Number of parallel sampling sequences
        gen_lengths: List of ints, number of tokens generated by each sequence
        block_size: Number of tokens per memory block
    
    Returns:
        Dictionary with memory usage statistics
    """
    prefill_blocks = prompt_length//block_size
    shared_prompt_blocks = prefill_blocks
    last_block = prompt_length - (prompt_length//block_size) * block_size
    flag = prompt_length%block_size
    cow_events = 0
    total_physics_blocks = prefill_blocks
    total_logical_blocks = 0
    new_generation_blocks = 0
    memory_saved_pct = 0

    if flag == 0:
        for i in range(num_sequences):
            left_tokens = last_block+gen_lengths[i]
            new_blocks = 0
            if left_tokens%block_size==0:
                new_blocks = left_tokens//block_size
            else:
                new_blocks = left_tokens//block_size +1
            total_physics_blocks+=new_blocks
            total_logical_blocks += (new_blocks+prefill_blocks)
            new_generation_blocks += new_blocks
    else:
        cow_events = num_sequences-1
        for i in range(num_sequences):
            left_tokens = last_block + gen_lengths[i]
            new_blocks = 0
            if left_tokens%block_size==0:
                new_blocks = left_tokens//block_size
            else:
                new_blocks = left_tokens//block_size +1
            total_physics_blocks +=new_blocks
            total_logical_blocks += (new_blocks+prefill_blocks)
            new_generation_blocks += (new_blocks-1)
    memory_saved_pct = round((total_logical_blocks-total_physics_blocks)*100/total_logical_blocks,2)

    ans = {
        'total_physical_blocks': total_physics_blocks, 'total_logical_blocks': total_logical_blocks, 'shared_prompt_blocks': shared_prompt_blocks, 'cow_events': cow_events, 'new_generation_blocks': new_generation_blocks, 'memory_saved_pct': memory_saved_pct
    }
    return ans

    

